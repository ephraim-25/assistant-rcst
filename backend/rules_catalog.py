def execute_catalog_rules(text: str) -> List[RuleViolation]:
    """
    Exécute l'ensemble des règles granulaires du catalogue déterministe RCST sur le texte.
    Retourne la liste des violations détectées.
    """
    violations: List[RuleViolation] = []

    for rule in RCST_CATALOG:
        pat: re.Pattern = rule["pattern"]
        matches = list(pat.finditer(text))
        if matches:
            first_match = matches[0]
            excerpt_str = ""
            pos = first_match.start()
            if first_match.group(0).strip():
                excerpt_str, _ = _excerpt(text, first_match, context=35)

            violations.append(
                RuleViolation(
                    rule_id=rule["id"],
                    severity=rule["severity"],
                    title=rule["title"],
                    message=f"{rule['message']} {rule['fix']}",
                    excerpt=excerpt_str,
                    position=pos,
                )
            )

    return violations
